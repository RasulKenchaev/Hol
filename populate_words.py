def main():
    db.init_db()
    dialects = {d["key"] for d in db.get_dialects()}

    added = updated = skipped = unknown_dk = 0
    unknown_keys = set()

    for dk, lit, form, cat, pos in WORDS:
        if dk not in dialects:
            unknown_keys.add(dk)
            unknown_dk += 1
            continue
        result = db.add_word(dk, lit, form, cat, pos)
        if result == "added":
            added += 1
        elif result == "updated":
            updated += 1
        else:
            skipped += 1

    print("=" * 54)
    print("   НАТИҶАИ ПУРКУНӢ")
    print("=" * 54)
    print(f"  Илова шуд:   {added}")
    print(f"  Навсозӣ:     {updated}")
    print(f"  Мавҷуд буд:  {skipped}")
    print(f"  Ключ нест:   {unknown_dk}")
    if unknown_keys:
        print(f"  Ключҳои номаълум: {', '.join(sorted(unknown_keys))}")
