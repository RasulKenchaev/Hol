def analyze_dialect(text: str, api_key: str, on_result, on_error,
                    lit_words: list[str] | None = None):
    """Claude AI тавассути thread-и алоҳида."""

    def _build_prompt(text: str, lit_words: list[str] | None) -> str:
        parts = [
            "═══════════════════════════════════════════════",
            "ВАЗИФА 1 — МУАЙЯНИ ЛАҲҶА",
            "═══════════════════════════════════════════════",
            f"Матн: «{text}»",
            "",
            "1. Лаҳҷа/ноҳияро муайян кун",
            "2. Далелҳоро шарҳ деҳ — кадом калимаҳо нишонаи он ноҳиянд",
            "3. Агар омехта бошад, ҳамаро зикр кун",
            "4. Ҷавоби равшан ва мухтасар бидеҳ",
        ]
        if lit_words:
            lit_str = ", ".join(f"«{w}»" for w in lit_words)
            parts += [
                "",
                "═══════════════════════════════════════════════",
                "ВАЗИФА 2 — ТАҲЛИЛИ КАЛИМАҲОИ АДАБИИ ЁФТШУДА",
                "═══════════════════════════════════════════════",
                f"Ин калимаҳо дар матн ҳамчун шакли адабӣ (стандартӣ) муайян шуданд:",
                lit_str,
                "",
                "Барои ҳар калима нишон деҳ:",
                "• Маъно ва ҷузъи нутқ (исм, феъл, сифат…)",
                "• Решаи луғавӣ ё пайдоиш (агар маълум бошад)",
                "• Мисоли истифода дар ҷумла",
                "• Синоним ё калимаи наздик (агар дошта бошад)",
            ]
        return "\n".join(parts)

    def _run():
        try:
            client = anthropic.Anthropic(api_key=api_key)
            message = client.messages.create(
                model="claude-haiku-4-5",
                max_tokens=1536,
                system=SYSTEM_PROMPT,
                messages=[{
                    "role": "user",
                    "content": _build_prompt(text, lit_words)
                }]
            )
            on_result(message.content[0].text)
        except anthropic.AuthenticationError:
            on_error("Калиди API нодуруст аст.")
        except anthropic.APIConnectionError:
            on_error("Интернет кор намекунад. Офлайн-ҳолатро истифода баред.")
        except Exception as e:
            on_error(f"Хато: {e}")

    threading.Thread(target=_run, daemon=True).start()
