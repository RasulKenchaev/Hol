def main():
    db.init_db()

    existing = {d["key"] for d in db.get_dialects()}
    added = 0
    skipped = 0

    conn = db.get_connection()
    for key, name, region, order in NEW_DIALECTS:
        if key in existing:
            skipped += 1
            continue
        conn.execute(
            "INSERT OR IGNORE INTO dialects (key, name, region, sort_order) VALUES (?,?,?,?)",
            (key, name, region, order)
        )
        added += 1

    conn.commit()
    conn.close()

    print(f"✅  Тамом!")
    print(f"   Илова шуд:    {added} ноҳия")
    print(f"   Аллакай буд:  {skipped} ноҳия")

    all_d = db.get_dialects()
    print(f"   Ҷамъан дар база: {len(all_d)} лаҳҷа/ноҳия")
    print()
    print("Ҳамаи ноҳияҳо:")
    for d in all_d:
        print(f"  [{d['key']:20s}] {d['name']:35s} — {d['region']}")


if __name__ == "__main__":
    main()
