import db

tests = [
    ("мерам",     "меравам"),
    ("гуфтему",   "гуфтем"),
    ("рафтему",   "рафтем"),
    ("мегӯям",    "мегӯям"),
    ("мехонам",   "мехонам"),
    ("мешавам",   "мешавам"),
    ("мекунам",   "мекунам"),
    ("мебинам",   "мебинам"),
    ("мегирам",   "мегирам"),
    ("нахондем",  "нахондем"),
    ("рафтам",    "рафтам"),
    ("хондам",    "хондам"),
    ("гуфтам",    "гуфтам"),
    ("намедунам", "намедонам"),
    ("мерамай",   "меравамад"),
    ("бародар",   "бародар"),
    ("китобро",   "китобро"),
    ("дастам",    "дастам"),
]

print("=== НАТИҶА ===")
all_ok = True
for word, expected in tests:
    r = db.morph_analyze_word(word)
    rec  = r["literary_reconstruction"]
    root = r["root"]["form"]
    suf  = r["suffix"]["form"]
    ok   = "OK" if rec == expected else "??"
    if ok == "??": all_ok = False
    print(f"  {ok} {word:16} реша={root:10} пасванд={suf:6} -> {rec:20} (кутиш: {expected})")

print()
print("Ҳамаи санҷишҳо:", "OK" if all_ok else "Мушкил дорад")
